"""Configuration loader for the GX470 scraper."""

import os
from pathlib import Path

import yaml

BASE_DIR = Path(__file__).resolve().parent


def load_yaml(filename: str) -> dict:
    filepath = BASE_DIR / filename
    # Fall back to .example file if the real config doesn't exist
    if not filepath.exists():
        example = BASE_DIR / f"{filename}.example"
        if example.exists():
            filepath = example
    with open(filepath, "r") as f:
        return yaml.safe_load(f)


def load_config() -> dict:
    return load_yaml("config.yaml")


def load_dealers() -> list[dict]:
    data = load_yaml("dealers.yaml")
    return data.get("dealers", [])


def get_env(key: str, required: bool = True) -> str | None:
    value = os.environ.get(key)
    if required and not value:
        raise EnvironmentError(f"Required environment variable '{key}' is not set.")
    return value


